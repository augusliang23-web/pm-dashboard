import test from 'node:test';
import assert from 'node:assert/strict';
import { normalizeDeliveryReportingPeriod, calculateDeliveryTrends } from '../shared/delivery-trends.mjs';
import { createDeliveryTrendsInput, loadDeliveryTrendsInput } from '../js/delivery-trends-adapter.mjs';
import { input,week,project } from '../shared/fixtures/delivery-trends.mjs';
test('stored ISO labels generated by getIsoWeekData normalize numerically across years',()=>{
 assert.deepEqual(normalizeDeliveryReportingPeriod({weekLabel:'W53 2020',weekDate:'Dec 28 - Jan 1'}),{year:2020,week:53});
 assert.deepEqual(normalizeDeliveryReportingPeriod({weekLabel:'W1 2021',weekDate:'Jan 4 - Jan 8'}),{year:2021,week:1});
 assert.deepEqual(normalizeDeliveryReportingPeriod({weekLabel:'W41 2026',weekDate:'Oct 5 - Oct 9'}),{year:2026,week:41});
});
test('invalid, ambiguous or contradictory period evidence never guesses a year',()=>{
 for(const record of [{weekLabel:'W41'},{weekLabel:'W53 2021'},{weekLabel:'W40 2026',reportingPeriod:{year:2026,week:41}},{weekLabel:'W41 2026',weekDate:'Oct 12 - Oct 16'},{weekLabel:'W41 2026',reportingPeriod:{year:2026,week:99}}])assert.equal(normalizeDeliveryReportingPeriod(record),null);
});
test('adapter preserves raw progress and normalizes only authorized period records',()=>{
 const record={__documentId:'W41-2026',weekLabel:'W41 2026',isReleased:true,projects:[project({progress:null})]};
 const result=createDeliveryTrendsInput({...input(),anchorWeekId:'W41-2026',weeks:[record],canReadWeek:()=>true,canReadProject:()=>true});
 assert.deepEqual(result.weeks[0].reportingPeriod,{year:2026,week:41});assert.equal(result.weeks[0].projects[0].progress,null);
});
test('anchor scope membership does not require progress; historical-only projects remain diagnostic',()=>{
 const r=calculateDeliveryTrends(input([week(40,[project(),project({projectId:'gone',code:'G'})]),week(41,[project({progress:null})])]));
 const active=r.projects.find(p=>p.projectId==='a');assert.equal(active.isInAnchorScope,true);assert.equal(active.currentCompletionPct,null);
 const gone=r.projects.find(p=>p.projectId==='gone');assert.equal(gone.isInAnchorScope,false);assert.equal(gone.comparable,false);
});
test('bounded browser history loader refuses truncation instead of inventing completeness',async()=>{
 let calls=0;const options={...input(),canReadWeek:()=>true,canReadProject:()=>true,readHistoryPage:async()=>{calls++;return {weeks:[week(41)],nextCursor:String(calls)}}};
 await assert.rejects(loadDeliveryTrendsInput(options),/history read limit/);assert.equal(calls,6);
});
test('bounded browser loader preserves calendar gaps and enforces auth before normalization',async()=>{
 const result=await loadDeliveryTrendsInput({...input(),canReadWeek:w=>w.weekId!=='private',canReadProject:p=>p.code!=='SECRET',readHistoryPage:async()=>({weeks:[week(39),week(41),{weekId:'private',projects:'SECRET'}],nextCursor:null})});
 const r=calculateDeliveryTrends(result);assert.equal(r.summary.weeklyProgressGainPp,null);assert.ok(!JSON.stringify(r).includes('SECRET'));
});
test('fresh historical revisions change recorded metrics and retain version diagnostics',()=>{
 const a=calculateDeliveryTrends(input([week(40,[project({progress:20})],{version:1}),week(41,[project({progress:30})],{version:2})]));
 const b=calculateDeliveryTrends(input([week(40,[project({progress:25})],{version:3}),week(41,[project({progress:30})],{version:2})]));
 assert.equal(a.summary.weeklyProgressGainPp,10);assert.equal(b.summary.weeklyProgressGainPp,5);assert.equal(b.weeklySeries.at(-2).recordVersion,3);
});
test('historical-only output uses last in-scope display metadata, never hidden current labels',()=>{
 const r=calculateDeliveryTrends(input([week(40,[project({name:'Visible Name',owner:'Visible PM'})]),week(41,[project({visibility:'archived',lifecycle:'completed',name:'PRIVATE-CURRENT',owner:'PRIVATE-PM'})])]));
 assert.equal(r.changes.exitedScope.length,1);assert.equal(r.changes.confirmedCompleted.length,1);
 assert.equal(r.projects[0].name,'Visible Name');assert.equal(r.projects[0].isInAnchorScope,false);
 assert.ok(!JSON.stringify(r).includes('PRIVATE'));
});
